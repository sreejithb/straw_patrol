def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--adapter", default="out/lora_B")
    ap.add_argument("--repo", default="sreejithb/fallacy-qwen2.5-1.5b-lora")
    ap.add_argument("--public", action="store_true", help="make the repo public (default: private)")
    args = ap.parse_args()
    adapter = ROOT / args.adapter
    api = HfApi()
    api.create_repo(args.repo, repo_type="model", private=not args.public, exist_ok=True)
    for name in ("adapter_model.safetensors", "adapter_config.json"):
        api.upload_file(path_or_fileobj=str(adapter / name), path_in_repo=name, repo_id=args.repo, repo_type="model")
    api.upload_file(path_or_fileobj=CARD.replace("REPO_ID", args.repo).encode(), path_in_repo="README.md",
                    repo_id=args.repo, repo_type="model")
    print(f"done: https://huggingface.co/{args.repo} ({'public' if args.public else 'private'})")


if __name__ == "__main__":
    main()
